import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const requireRelease = createRequire(new URL('../../shell/package.json', import.meta.url));
const {inspectConfiguration} = require('../../scripts/northstar-active-config-inspect.cjs');
const {inspectSettings, adoptSettings} = require('../../shell/runtime/settings-version.cjs');
test('active configuration receipt is read-only, redacts content and distinguishes an untracked/edited home', t => {
  const root = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'northstar-active-config-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  const home = path.join(root, 'home'); fs.mkdirSync(home, {mode: 0o700});
  const template = path.join(root, 'template.yaml');
  const raw = 'llm-pi-ai:\n  providers:\n    powertokens:\n      models:\n        - id: seed-2-0-lite-260228\n      apiKey: private-fixture-do-not-print\n';
  fs.writeFileSync(template, raw, {mode: 0o600});
  fs.writeFileSync(path.join(home, 'settings.yaml'), raw, {mode: 0o600});
  const inspect = () => inspectConfiguration({home, template, requireRelease});
  const before = fs.readdirSync(home);
  const first = inspect();
  assert.equal(first.settingsStatus, 'untracked');
  assert.equal(first.matchesActiveReleaseTemplate, true);
  assert.equal(first.models['deepseek-flash'], false);
  assert.equal(first.models['seed-2-0-lite-260228'], true);
  assert.equal(first.providerCalls, 0);
  assert.equal(JSON.stringify(first).includes('private-fixture'), false);
  assert.deepEqual(fs.readdirSync(home), before);
  assert.equal(fs.readFileSync(path.join(home, 'settings.yaml'), 'utf8'), raw);
  adoptSettings({home, template, expected: inspectSettings({home, template}), reviewed: true});
  assert.equal(inspect().settingsStatus, 'current');
  fs.appendFileSync(path.join(home, 'settings.yaml'), '# operator edit\n');
  const edited = inspect();
  assert.equal(edited.settingsStatus, 'operator-edited');
  assert.equal(edited.baselineMatchesActive, false);
  assert.equal(edited.matchesActiveReleaseTemplate, false);
});
