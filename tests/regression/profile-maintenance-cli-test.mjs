import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { makeProfile } = require('../../shell/runtime/dsh-adapter.cjs');
const cli = path.resolve('scripts/northstar-profile.cjs');
const run = (...args) => spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8' });
test('offline CLI rebuild retains old user content and new profile verifies', t => {
  const temp = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'northstar-profile-cli-'));
  t.after(() => fs.rmSync(temp, { recursive: true, force: true }));
  const home = path.join(temp, 'home');
  const template = path.resolve('shell/dsh-settings.yaml');
  const runner = path.resolve('shell/persistent-runner.mjs');
  const profile = makeProfile(home, template, runner);
  const manifestPath = path.join(profile.dir, 'northstar-profile-manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const prior = 'previous valid runner';
  fs.writeFileSync(path.join(profile.dir, 'persistent-runner.mjs'), prior);
  manifest.files['persistent-runner.mjs'] = crypto.createHash('sha256').update(prior).digest('hex');
  fs.writeFileSync(manifestPath, JSON.stringify(manifest));
  fs.writeFileSync(path.join(profile.dir, 'operator-note.txt'), 'retain me');
  assert.throws(() => makeProfile(home, template, runner), { code: 'PROFILE_STALE' });
  const denied = run('rebuild', '--home', home);
  assert.equal(denied.status, 1);
  assert.equal(fs.readFileSync(path.join(profile.dir, 'persistent-runner.mjs'), 'utf8'), prior);
  const rebuilt = run('rebuild', '--home', home, '--offline');
  assert.equal(rebuilt.status, 0, rebuilt.stderr);
  const { backupDir } = JSON.parse(rebuilt.stdout);
  assert.equal(fs.readFileSync(path.join(backupDir, 'operator-note.txt'), 'utf8'), 'retain me');
  assert.equal(fs.readFileSync(path.join(backupDir, 'persistent-runner.mjs'), 'utf8'), prior);
  assert.equal(fs.existsSync(path.join(profile.dir, 'operator-note.txt')), false);
  assert.equal(makeProfile(home, template, runner).dir, profile.dir);
  const invalid = run('restore-backup', '--home', home, '--offline');
  assert.equal(invalid.status, 1);
  assert.equal(JSON.parse(invalid.stderr).code, 'PROFILE_RECOVERY_INVALID');
  assert.equal(fs.readFileSync(path.join(backupDir, 'operator-note.txt'), 'utf8'), 'retain me');
});
