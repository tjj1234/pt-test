import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createStorage } = require('../../shell/storage/index.cjs');
const { createTaskStore } = require('../../shell/tasks/store.cjs');

test('persistent task store: ownership, atomic claims, event order, revisions and recovery', async () => {
  assert.equal(Object.keys(process.env).some((key) => key.startsWith('PT_PG_') && process.env[key]), false, 'No external PG configuration allowed');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'northstar-task-store-'));
  const opts = { dataDir: path.join(tmp, 'db'), masterKeyFile: path.join(tmp, 'key') };
  let storage;
  try {
    storage = await createStorage(opts);
    let store = createTaskStore(storage.adapter);
    const regA = await storage.repositories.auth.register({ username: 'task-user-a', password: 'FixturePass123' });
    const regB = await storage.repositories.auth.register({ username: 'task-user-b', password: 'FixturePass123' });
    assert.equal(regA.ok && regB.ok, true);
    const a = { userId: regA.user.id, tenantId: regA.user.tenant_id };
    const b = { userId: regB.user.id, tenantId: regB.user.tenant_id };
    const convA = await storage.repositories.conversations.create(a.userId);
    const convB = await storage.repositories.conversations.create(b.userId);
    const input = (key = 'key-1', extra = {}) => ({ conversationId: convA.id, idempotencyKey: key, policyVersion: 'policy-1', request: { question: 'persist me', attachments: [] }, ...extra });
    const attempts = await Promise.all(Array.from({ length: 12 }, () => store.createRun(a, input())));
    const id = attempts[0].run.runId;
    assert.equal(new Set(attempts.map((x) => x.run.runId)).size, 1);
    assert.equal(attempts.filter((x) => !x.replayed).length, 1);
    assert.equal((await storage.adapter.query('SELECT count(*)::int AS count FROM agent_runs')).rows[0].count, 1);
    assert.equal((await store.eventsAfter(a, id)).events.length, 1);
    await assert.rejects(store.createRun(a, input('key-1', { request: { question: 'other' } })), { code: 'IDEMPOTENCY_CONFLICT', statusCode: 409 });
    await assert.rejects(store.createRun(a, input('cross', { conversationId: convB.id })), { code: 'NOT_FOUND' });
    await assert.rejects(store.createRun(a, input('cross2', { tenantId: b.tenantId })), { code: 'FORBIDDEN' });
    await assert.rejects(store.createRun(a, input('cross3', { workspaceId: 'other' })), { code: 'FORBIDDEN' });
    await assert.rejects(store.getRun(b, id), { code: 'NOT_FOUND' });
    await assert.rejects(store.eventsAfter(b, id), { code: 'NOT_FOUND' });
    await assert.rejects(store.appendEvent(b, id, { type: 'delta', payload: { text: 'wrong' } }), { code: 'NOT_FOUND' });
    assert.equal((await store.listRuns(b)).runs.length, 0);
    const ownB = await store.createRun(b, { ...input(), conversationId: convB.id });
    assert.notEqual(ownB.run.runId, id, 'same client key in another identity has independent scope');

    const leaseA = await store.acquireLease(a, id, 'worker-a', 10000);
    assert.equal(leaseA.acquired, true);
    assert.equal((await store.acquireLease(a, id, 'worker-b', 10000)).acquired, false, 'live lease excludes a competing worker');
    await store.renewLease(a, id, 'worker-a', 10000);
    await assert.rejects(store.renewLease(a, id, 'worker-b', 10000), { code: 'LEASE_LOST' });
    await storage.adapter.query("UPDATE agent_runs SET lease_expires_at=now()-interval '1 second' WHERE run_id=$1", [id]);
    assert.equal((await store.acquireLease(a, id, 'worker-b', 10000)).acquired, true, 'expired lease can be taken over');
    assert.equal(await store.releaseLease(a, id, 'worker-a'), false, 'old owner cannot release successor lease');
    assert.equal(await store.releaseLease(a, id, 'worker-b'), true);

    const running = await store.transition(a, id, 'running', 0);
    assert.equal(running.revision, 1);
    const races = await Promise.allSettled([store.transition(a, id, 'awaiting_confirmation', 1), store.transition(a, id, 'waiting_external', 1)]);
    assert.equal(races.filter((x) => x.status === 'fulfilled').length, 1);
    assert.equal(races.find((x) => x.status === 'rejected').reason.code, 'REVISION_CONFLICT');
    const state = await store.getRun(a, id);
    await store.transition(a, id, 'running', state.revision);
    const deltas = await Promise.all(Array.from({ length: 15 }, (_, i) => store.appendEvent(a, id, { eventId: randomUUID(), type: 'delta', payload: { text: 'chunk-' + i } })));
    assert.equal(new Set(deltas.map((x) => x.seq)).size, 15);
    const replayId = randomUUID();
    const e = await store.appendEvent(a, id, { eventId: replayId, type: 'delta', payload: { text: 'stable' } });
    assert.deepEqual(await store.appendEvent(a, id, { eventId: replayId, type: 'delta', payload: { text: 'stable' } }), e);
    await assert.rejects(store.appendEvent(a, id, { eventId: replayId, type: 'delta', payload: { text: 'changed' } }), { code: 'EVENT_ID_CONFLICT' });
    await assert.rejects(store.appendEvent(a, id, { runId: randomUUID(), type: 'delta', payload: {} }), { code: 'EVENT_SCOPE_MISMATCH' });
    await assert.rejects(store.appendEvent(a, id, { type: 'done', payload: { state: 'completed' } }), { code: 'EVENT_STATE_MISMATCH' });
    await assert.rejects(store.appendEvent(a, id, { type: 'delta', payload: false }), { code: 'CONTRACT_INVALID' });
    const page = await store.eventsAfter(a, id, { limit: 2 });
    assert.equal(page.hasMore, true);
    assert.equal(page.nextCursor, 2);
    const remaining = await store.eventsAfter(a, id, { after: page.nextCursor });
    const all = [...page.events, ...remaining.events];
    assert.deepEqual(all.map((x) => x.seq), all.map((_, i) => i + 1));
    await assert.rejects(store.eventsAfter(a, id, { after: -1 }), { code: 'CONTRACT_INVALID' });

    const second = (await store.createRun(a, input('key-2'))).run;
    await assert.rejects(store.appendEvent(a, second.runId, { eventId: replayId, type: 'delta', payload: { text: 'stable' } }), { code: 'EVENT_ID_CONFLICT' });
    assert.deepEqual((await store.eventsAfter(a, second.runId)).events.map((x) => x.seq), [1], 'failed append rolls back seq claim');
    const listPage = await store.listRuns(a, { limit: 1 });
    const listTail = await store.listRuns(a, { afterRunId: listPage.nextCursor, limit: 1 });
    assert.equal(new Set([...listPage.runs, ...listTail.runs].map((x) => x.runId)).size, 2);

    let ext = (await store.createRun(a, input('external-unknown'))).run;
    ext = await store.transition(a, ext.runId, 'running', 0);
    ext = await store.recordExternalIntent(a, ext.runId, { provider: 'fixture', operationKey: 'stable-upstream-key', expectedRevision: ext.revision });
    assert.equal(ext.externalTaskId, null);
    assert.equal(ext.reconciliation, 'needs_reconciliation');
    let known = (await store.createRun(a, input('external-known'))).run;
    known = await store.transition(a, known.runId, 'running', 0);
    known = await store.recordExternalIntent(a, known.runId, { provider: 'fixture', operationKey: 'known-key', expectedRevision: known.revision });
    known = await store.recordExternalTaskId(a, known.runId, { taskId: 'provider-task-1', expectedRevision: known.revision });
    assert.equal(known.externalTaskId, 'provider-task-1');
    const eventCount = (await store.eventsAfter(a, id)).events.length;
    await storage.close(); storage = null;
    storage = await createStorage(opts);
    store = createTaskStore(storage.adapter);
    assert.equal((await store.eventsAfter(a, id)).events.length, eventCount);
    assert.equal((await store.createRun(a, input())).run.runId, id, 'claim survives restart');
    await store.recoverInterrupted(a);
    assert.equal((await store.getRun(a, id)).state, 'interrupted');
    assert.equal((await store.getRun(a, second.runId)).state, 'interrupted', 'queued work without a live worker is interrupted during restart recovery');
    const unknownRecovered = await store.getRun(a, ext.runId);
    assert.equal(unknownRecovered.externalState, 'unknown');
    assert.equal(unknownRecovered.state, 'waiting_external');
    assert.equal(unknownRecovered.reconciliation, 'needs_reconciliation');
    assert.equal((await store.getRun(a, known.runId)).externalState, 'pending_query');
    assert.equal((await store.getRun(a, known.runId)).externalTaskId, 'provider-task-1');
    await store.recoverInterrupted(a);
    assert.deepEqual(await store.getRun(a, ext.runId), unknownRecovered, 'repeat recovery does not resubmit or mutate unknown task');
    await assert.rejects(store.transition(a, id, 'running', (await store.getRun(a, id)).revision), { code: 'INVALID_TRANSITION' });
    await assert.rejects(store.appendEvent(a, id, { type: 'delta', payload: {} }), { code: 'RUN_TERMINAL' });
    assert.equal((await storage.adapter.query('SELECT count(*)::int AS count FROM agent_runs')).rows[0].count, 5, 'recovery never creates replacement paid runs');
    const terminalEvents = (await store.eventsAfter(a, id)).events;
    const done = terminalEvents.find((x) => x.type === 'done');
    assert.ok(done);
    assert.deepEqual(await store.appendEvent(a, id, done), done, 'same eventId terminal replay is idempotent');
    await assert.rejects(store.appendEvent(a, id, { type: 'done', payload: { state: 'interrupted' } }), { code: 'TERMINAL_EVENT_EXISTS' });
    assert.equal((await store.eventsAfter(a, id)).events.filter((x) => x.type === 'done').length, 1);
    const forgedDone = { ...done, eventId: randomUUID(), seq: terminalEvents.at(-1).seq + 1 };
    await assert.rejects(storage.adapter.query('INSERT INTO agent_run_events(event_id,run_id,seq,event) VALUES($1,$2,$3,$4::jsonb)', [forgedDone.eventId, id, forgedDone.seq, JSON.stringify(forgedDone)]), { code: '23505' }, 'DB uniqueness prevents bypassing store terminal dedupe');
    const retained = await store.eventsAfter(a, ext.runId);
    await storage.repositories.conversations.remove(a.userId, convA.id);
    assert.equal(await storage.repositories.conversations.get(a.userId, convA.id), null);
    assert.equal((await store.getRun(a, ext.runId)).externalOperationKey, 'stable-upstream-key');
    assert.deepEqual(await store.eventsAfter(a, ext.runId), retained, 'conversation deletion retains external intent and audit events');
    await assert.rejects(store.createRun(a, input('deleted-conversation')), { code: 'NOT_FOUND' });
  } finally {
    try { if (storage) await storage.close(); }
    finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  }
});
