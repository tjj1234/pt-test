import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createStorage } = require('../../shell/storage/index.cjs');
const { createTaskStore } = require('../../shell/tasks/store.cjs');
const { normalizeChatRequest, bindChatModelSelection, chatRequestIdempotencyView, validateStoredChatRequest, isReplayableChatRequest, captureDurableChatAttachments, verifyDurableChatAttachments } = require('../../shell/tasks/chat-request.cjs');
test('model snapshot stays server owned, canonical, replayable and preserves attachment evidence', async t => {
  const tenantId = '11111111-1111-4111-8111-111111111111';
  const identity = { userId: 'fixture-user', tenantId };
  assert.throws(() => normalizeChatRequest({ message: 'hello', modelSelection: { requestedModelId: 'injected' } }, tenantId));
  const legacy = normalizeChatRequest({ message: 'hello' }, tenantId);
  const request = bindChatModelSelection(legacy, tenantId, 'model-a');
  assert.equal(request.schemaVersion, 3);
  assert.equal(isReplayableChatRequest(request, tenantId), true);
  assert.deepEqual(validateStoredChatRequest(request, tenantId), request);
  assert.deepEqual(chatRequestIdempotencyView(request, tenantId), legacy);
  assert.throws(() => validateStoredChatRequest({ ...request, modelSelection: { requestedModelId: 'a', apiKey: 'injected' } }, tenantId));
  assert.throws(() => bindChatModelSelection(legacy, tenantId, '  model-a'));
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'northstar-model-attachment-'));
  t.after(() => fs.rmSync(temp, { recursive: true, force: true }));
  const tenantRoot = path.join(temp, tenantId); fs.mkdirSync(tenantRoot);
  fs.writeFileSync(path.join(tenantRoot, 'sample.txt'), 'content');
  const captured = await captureDurableChatAttachments(normalizeChatRequest({ message: 'read', documents: [`/uploads/${tenantId}/sample.txt`] }, tenantId), { identity, uploadsRoot: temp });
  const bound = bindChatModelSelection(captured, tenantId, 'model-b');
  assert.equal(isReplayableChatRequest(bound, tenantId), true);
  assert.deepEqual(chatRequestIdempotencyView(bound, tenantId), captured);
  assert.deepEqual(await verifyDurableChatAttachments(bound, { identity, uploadsRoot: temp }), bound);
  fs.writeFileSync(path.join(tenantRoot, 'sample.txt'), 'changed');
  await assert.rejects(verifyDurableChatAttachments(bound, { identity, uploadsRoot: temp }), { code: 'CHAT_ATTACHMENT_CHANGED' });
});
test('same idempotency key replays original model snapshot and queued recovery claims v3', async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'northstar-model-idempotency-'));
  const storage = await createStorage({ dataDir: path.join(temp, 'db'), masterKeyFile: path.join(temp, 'key') });
  t.after(async () => { await storage.close(); fs.rmSync(temp, { recursive: true, force: true }); });
  const registered = await storage.repositories.auth.register({ username: 'snapshot-fixture', password: 'FixturePass123' });
  const identity = { userId: registered.user.id, tenantId: registered.user.tenant_id };
  const conv = await storage.repositories.conversations.create(identity.userId);
  const store = createTaskStore(storage.adapter);
  const base = normalizeChatRequest({ message: 'hello' }, identity.tenantId);
  const a = bindChatModelSelection(base, identity.tenantId, 'model-a');
  const b = bindChatModelSelection(base, identity.tenantId, 'model-b');
  const input = request => ({ conversationId: conv.id, idempotencyKey: 'same-client-command', request });
  const first = await store.createRun(identity, input(a));
  const replay = await store.createRun(identity, input(b));
  assert.equal(replay.replayed, true); assert.equal(replay.run.runId, first.run.runId);
  await assert.rejects(store.createRun(identity, input(bindChatModelSelection(normalizeChatRequest({ message: 'different' }, identity.tenantId), identity.tenantId, 'model-b'))), { code: 'IDEMPOTENCY_CONFLICT' });
  const claimed = await store.claimReplayableQueuedRuns('recovery-worker');
  assert.equal(claimed.length, 1);
  assert.equal(claimed[0].request.modelSelection.requestedModelId, 'model-a');
});
