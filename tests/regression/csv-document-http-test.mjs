    assert.ok(note.includes(`[csv:${contentHash}:${refHash}:R1C1]`));
    assert.match(note, /R1C1\] sourceLine=1; sourceColumn=1; value=""/);
    assert.match(note, /R1C2\] sourceLine=1; sourceColumn=2; value="0"/);
